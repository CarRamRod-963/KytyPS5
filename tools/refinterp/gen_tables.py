"""Generates the RDNA2 decode tables of the reference interpreter from AMD's machine-readable ISA.

usage: python -I gen_tables.py <amdgpu_isa_rdna1.xml> <out.inc> [<amdgpu_isa_rdna2.xml> NAME,NAME...]

Source: AMD GPUOpen machine-readable ISA (AMD_GPU_MR_ISA_XML_2026_08_06.zip, MIT license). The PS5 GPU
runs RDNA1 shader code (V_MAD_F32, V_MAC_F32, V_MADAK_F32... exist only in amdgpu_isa_rdna1.xml) plus
the BVH ray instructions of RDNA2, which are imported by name from amdgpu_isa_rdna2.xml. Only encodings, bit layouts, opcodes and operand descriptions come from the XML; the
semantics are written by hand in refinterp.cpp.
"""
import sys
import xml.etree.ElementTree as ET

xml_path, out_path = sys.argv[1], sys.argv[2]
isa = ET.parse(xml_path).getroot().find('ISA')
extra_isa, extra_names = None, set()
if len(sys.argv) > 4:
    extra_isa = ET.parse(sys.argv[3]).getroot().find('ISA')
    extra_names = set(sys.argv[4].split(','))

# Base encodings recognised from the first dword, with their field layouts.
BASE = ['ENC_SOP1', 'ENC_SOPC', 'ENC_SOPP', 'ENC_SOPK', 'ENC_SOP2', 'ENC_SMEM', 'ENC_VOP1', 'ENC_VOPC',
        'ENC_VOP2', 'ENC_VINTRP', 'ENC_VOP3', 'ENC_VOP3P', 'ENC_DS', 'ENC_MUBUF', 'ENC_MTBUF', 'ENC_MIMG',
        'ENC_EXP', 'ENC_FLAT', 'VOP3_SDST_ENC', 'VOP1_VOP_SDWA', 'VOP2_VOP_SDWA', 'VOPC_VOP_SDWA_SDST_ENC',
        'VOP2_VOP_SDWA_SDST_ENC', 'VOP1_VOP_DPP16', 'VOP2_VOP_DPP16', 'VOP1_VOP_DPP8', 'VOP2_VOP_DPP8']
encodings = {}
for e in isa.find('Encodings').findall('Encoding'):
    name = e.findtext('EncodingName')
    fields = {}
    for f in e.find('MicrocodeFormat').find('BitMap').findall('Field'):
        fields[f.findtext('FieldName')] = [(int(r.findtext('BitOffset')), int(r.findtext('BitCount')))
                                           for r in f.find('BitLayout').findall('Range')]
    ident = e.find('EncodingIdentifiers')
    first = ident.find('EncodingIdentifier').text if ident is not None and ident.find('EncodingIdentifier') is not None else None
    encodings[name] = dict(order=int(e.get('Order')), bits=int(e.findtext('BitCount')), fields=fields, first=first)

def field_value(bits_text, layout):
    # Identifier strings are MSB first over the encoding's bit count (first dword for 32-bit masks).
    n = len(bits_text)
    value = int(bits_text, 2)
    out, shift = 0, 0
    for off, cnt in layout:
        out |= ((value >> off) & ((1 << cnt) - 1)) << shift
        shift += cnt
    return out

lines = ['// Generated by gen_tables.py from %s (+ %s) (AMD GPUOpen, MIT). Do not edit.' % (xml_path.split('/')[-1], ','.join(sorted(extra_names)) or '-'),
         '// Source data: Copyright (c) 2026 Advanced Micro Devices, Inc., or its affiliates. MIT License: LICENSES/AMD-GPU-MR-ISA-MIT.txt.', '']
lines.append('struct GenField { const char* name; uint8_t ranges; uint8_t offset[2]; uint8_t count[2]; };')
lines.append('struct GenEncoding { const char* name; int order; uint32_t bits; uint32_t enc_offset; uint32_t enc_count; uint32_t enc_value; const GenField* fields; uint32_t field_count; };')
for name in BASE:
    e = encodings[name]
    lines.append('static const GenField kFields_%s[] = {' % name)
    for fname, layout in sorted(e['fields'].items()):
        offs = [o for o, _ in layout] + [0]
        cnts = [c for _, c in layout] + [0]
        lines.append('    {"%s", %d, {%d, %d}, {%d, %d}},' % (fname, len(layout), offs[0], offs[1], cnts[0], cnts[1]))
    lines.append('};')
lines.append('static const GenEncoding kEncodings[] = {')
for name in BASE:
    e = encodings[name]
    enc = e['fields']['ENCODING'][0]
    value = field_value(e['first'], [enc]) if e['first'] else 0
    lines.append('    {"%s", %d, %d, %d, %d, 0x%x, kFields_%s, %d},' % (name, e['order'], e['bits'], enc[0], enc[1], value,
                                                                     name, len(e['fields'])))
lines.append('};')

# Instructions: (encoding, opcode) -> name; also operand sizes/format of each instruction encoding.
names = []
table = []
instructions = list(isa.find('Instructions').findall('Instruction'))
if extra_isa is not None:
    have = {i.findtext('InstructionName') for i in instructions}
    for i in extra_isa.find('Instructions').findall('Instruction'):
        if i.findtext('InstructionName') in extra_names and i.findtext('InstructionName') not in have:
            instructions.append(i)
for inst in instructions:
    name = inst.findtext('InstructionName')
    names.append(name)
    for ie in inst.find('InstructionEncodings').findall('InstructionEncoding'):
        enc = ie.findtext('EncodingName')
        if ie.findtext('EncodingCondition') not in ('default', None):
            continue
        ops = []
        for o in ie.find('Operands').findall('Operand'):
            ops.append('%s:%s:%s:%s:%s' % (o.findtext('FieldName') or '-', o.findtext('OperandType'), o.findtext('OperandSize'),
                                           o.findtext('DataFormatName'), 'o' if o.get('Output') == 'true' else 'i'))
        table.append((enc, int(ie.findtext('Opcode')), name, ' '.join(ops)))
# Instructions that exist only with a trailing literal (V_MADAK/MADMK/FMAAK/FMAMK, S_SETREG_IMM32_B32)
# are listed under *_INST_LITERAL; the decoder finds them by their base encoding.
alias = {'VOP2_INST_LITERAL': 'ENC_VOP2', 'SOPK_INST_LITERAL': 'ENC_SOPK'}
have = {(e, o) for e, o, _, _ in table}
for enc, opc, name, ops in list(table):
    if enc in alias and (alias[enc], opc) not in have:
        table.append((alias[enc], opc, name, ops))
        have.add((alias[enc], opc))
names = sorted(set(names))
lines.append('enum class Op : uint16_t {')
lines.append('    INVALID,')
for n in names:
    lines.append('    %s,' % n)
lines.append('    COUNT')
lines.append('};')
lines.append('static const char* const kOpNames[] = {"INVALID", %s};' % ', '.join('"%s"' % n for n in names))
lines.append('struct GenInstruction { const char* encoding; uint32_t opcode; Op op; const char* operands; };')
lines.append('static const GenInstruction kInstructions[] = {')
for enc, opc, name, ops in sorted(table):
    lines.append('    {"%s", %d, Op::%s, "%s"},' % (enc, opc, name, ops))
lines.append('};')
open(out_path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('encodings', len(BASE), 'instructions', len(names), 'encoding entries', len(table))
